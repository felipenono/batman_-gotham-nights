// Este arquivo cuida de desenhar a alternativa vetorial de batman.
import { APARENCIA } from "../../../config/configuracao.js";
const estiloVisual = APARENCIA.batman;

// ===== DEPENDÊNCIAS E CONFIGURAÇÕES =====
export const batman = {
  width: 42,
  height: 72,
  // Desenha a alternativa vetorial quando a imagem do personagem não está disponível.
  paint(contexto) {
    if (!this.alive) return;
    if (this.invulnerable > 0 && Math.floor(this.invulnerable / 4) % 2 === 0) {
      return;
    }
    contexto.save();
    contexto.translate(this.x + this.w / 2, this.y + this.h);
    contexto.scale(this.facing, 1);
    const isRunning = Math.abs(this.vx) > 0.5 && this.onGround;
    const isJumping = !this.onGround;
    const isThrowing = this.throwAnimTimer > 0;
    const breathe = Math.sin(this.animTime * 2) * 1.5;
    contexto.save();
    contexto.fillStyle = estiloVisual.preenchimento1;
    contexto.beginPath();
    const capeShoulderX = -10;
    const capeShoulderY = -54 + breathe;
    contexto.moveTo(capeShoulderX, capeShoulderY);
    if (isJumping) {
      const wingFlare = Math.sin(this.animTime * 4) * 6;
      contexto.quadraticCurveTo(-45 - wingFlare, -30, -55, 4);
      contexto.lineTo(-40, 0);
      contexto.lineTo(-28, 6);
      contexto.lineTo(-15, 2);
      contexto.lineTo(8, -50 + breathe);
    } else {
      const wave = Math.sin(this.animTime * 4 - this.vx * 0.4) * 6;
      const trail = -this.vx * 3.5;
      contexto.quadraticCurveTo(-26 + trail, -25 + breathe, -32 + trail + wave, 2);
      contexto.lineTo(-24 + trail * 0.8, -2);
      contexto.lineTo(-14 + trail * 0.5, 3);
      contexto.lineTo(-2, -2);
      contexto.lineTo(8, -52 + breathe);
    }
    contexto.closePath();
    contexto.fill();
    contexto.strokeStyle = estiloVisual.contorno2;
    contexto.lineWidth = 1.5;
    contexto.stroke();
    contexto.restore();
    const legOffset = isRunning ? Math.sin(this.animTime * 6) * 10 : 0;
    contexto.fillStyle = estiloVisual.preenchimento3;
    contexto.fillRect(-14 - legOffset * 0.5, -24, 9, 14);
    contexto.fillStyle = estiloVisual.preenchimento4;
    contexto.fillRect(-15 - legOffset * 0.6, -10, 10, 10);
    contexto.fillStyle = estiloVisual.preenchimento5;
    contexto.fillRect(-16 - legOffset * 0.6, -2, 12, 3);
    contexto.fillStyle = estiloVisual.preenchimento6;
    contexto.fillRect(4 + legOffset * 0.5, -24, 9, 14);
    contexto.fillStyle = estiloVisual.preenchimento4;
    contexto.fillRect(4 + legOffset * 0.6, -10, 11, 10);
    contexto.fillStyle = estiloVisual.preenchimento5;
    contexto.fillRect(3 + legOffset * 0.6, -2, 13, 3);
    const torsoY = -52 + breathe;
    contexto.fillStyle = estiloVisual.preenchimento9;
    contexto.beginPath();
    contexto.roundRect(-16, torsoY + 12, 32, 22, 3);
    contexto.fill();
    const chestGrad = contexto.createLinearGradient(-15, torsoY, 15, torsoY + 22);
    chestGrad.addColorStop(0, estiloVisual.gradiente10);
    chestGrad.addColorStop(1, estiloVisual.gradiente11);
    contexto.fillStyle = chestGrad;
    contexto.beginPath();
    contexto.moveTo(-15, torsoY + 8);
    contexto.lineTo(0, torsoY + 11);
    contexto.lineTo(15, torsoY + 8);
    contexto.lineTo(14, torsoY + 20);
    contexto.lineTo(0, torsoY + 22);
    contexto.lineTo(-14, torsoY + 20);
    contexto.closePath();
    contexto.fill();
    contexto.strokeStyle = estiloVisual.contorno12;
    contexto.lineWidth = 1.2;
    contexto.beginPath();
    contexto.moveTo(0, torsoY + 8);
    contexto.lineTo(0, torsoY + 22);
    contexto.stroke();
    contexto.fillStyle = estiloVisual.preenchimento4;
    contexto.beginPath();
    const symY = torsoY + 13;
    contexto.moveTo(0, symY + 4);
    contexto.lineTo(5, symY + 1);
    contexto.lineTo(9, symY - 3);
    contexto.lineTo(5, symY - 1);
    contexto.lineTo(2, symY - 4);
    contexto.lineTo(1, symY - 2);
    contexto.lineTo(-1, symY - 2);
    contexto.lineTo(-2, symY - 4);
    contexto.lineTo(-5, symY - 1);
    contexto.lineTo(-9, symY - 3);
    contexto.lineTo(-5, symY + 1);
    contexto.closePath();
    contexto.fill();
    const beltY = torsoY + 22;
    contexto.fillStyle = estiloVisual.preenchimento14;
    contexto.fillRect(-15, beltY, 30, 6);
    contexto.fillStyle = estiloVisual.preenchimento15;
    contexto.fillRect(-4, beltY - 1, 8, 8);
    contexto.fillStyle = estiloVisual.preenchimento16;
    contexto.fillRect(-2, beltY + 1, 4, 4);
    contexto.fillStyle = estiloVisual.preenchimento17;
    contexto.fillRect(-14, beltY + 1, 4, 5);
    contexto.fillRect(-9, beltY + 1, 4, 5);
    contexto.fillRect(5, beltY + 1, 4, 5);
    contexto.fillRect(10, beltY + 1, 4, 5);
    contexto.fillStyle = estiloVisual.preenchimento9;
    contexto.fillRect(-18, torsoY + 8, 6, 16);
    contexto.fillStyle = estiloVisual.preenchimento19;
    contexto.fillRect(-20, torsoY + 18, 7, 10);
    contexto.fillStyle = estiloVisual.preenchimento20;
    contexto.beginPath();
    contexto.moveTo(-20, torsoY + 19);
    contexto.lineTo(-24, torsoY + 21);
    contexto.lineTo(-20, torsoY + 22);
    contexto.moveTo(-20, torsoY + 22);
    contexto.lineTo(-24, torsoY + 24);
    contexto.lineTo(-20, torsoY + 25);
    contexto.moveTo(-20, torsoY + 25);
    contexto.lineTo(-24, torsoY + 27);
    contexto.lineTo(-20, torsoY + 28);
    contexto.fill();
    contexto.fillStyle = estiloVisual.gradiente11;
    if (isThrowing) {
      contexto.fillRect(8, torsoY + 8, 18, 6);
      contexto.fillStyle = estiloVisual.preenchimento19;
      contexto.fillRect(20, torsoY + 7, 10, 8);
      contexto.fillStyle = estiloVisual.preenchimento20;
      contexto.beginPath();
      contexto.moveTo(22, torsoY + 15);
      contexto.lineTo(20, torsoY + 19);
      contexto.lineTo(24, torsoY + 15);
      contexto.moveTo(25, torsoY + 15);
      contexto.lineTo(23, torsoY + 19);
      contexto.lineTo(27, torsoY + 15);
      contexto.moveTo(28, torsoY + 15);
      contexto.lineTo(26, torsoY + 19);
      contexto.lineTo(30, torsoY + 15);
      contexto.fill();
    } else {
      contexto.fillRect(11, torsoY + 8, 7, 16);
      contexto.fillStyle = estiloVisual.preenchimento19;
      contexto.fillRect(11, torsoY + 18, 8, 10);
      contexto.fillStyle = estiloVisual.preenchimento20;
      contexto.beginPath();
      contexto.moveTo(11, torsoY + 19);
      contexto.lineTo(7, torsoY + 21);
      contexto.lineTo(11, torsoY + 22);
      contexto.moveTo(11, torsoY + 22);
      contexto.lineTo(7, torsoY + 24);
      contexto.lineTo(11, torsoY + 25);
      contexto.moveTo(11, torsoY + 25);
      contexto.lineTo(7, torsoY + 27);
      contexto.lineTo(11, torsoY + 28);
      contexto.fill();
    }
    const headY = torsoY - 14;
    contexto.fillStyle = estiloVisual.preenchimento19;
    contexto.fillRect(-6, headY + 10, 12, 6);
    contexto.fillStyle = estiloVisual.preenchimento19;
    contexto.beginPath();
    contexto.arc(0, headY + 4, 11, Math.PI, 0, false);
    contexto.lineTo(11, headY + 11);
    contexto.lineTo(-11, headY + 11);
    contexto.closePath();
    contexto.fill();
    contexto.beginPath();
    contexto.moveTo(-10, headY + 2);
    contexto.lineTo(-12, headY - 10);
    contexto.lineTo(-6, headY - 1);
    contexto.moveTo(6, headY - 1);
    contexto.lineTo(12, headY - 10);
    contexto.lineTo(10, headY + 2);
    contexto.closePath();
    contexto.fill();
    contexto.fillStyle = estiloVisual.preenchimento28;
    contexto.beginPath();
    contexto.moveTo(-5, headY + 7);
    contexto.lineTo(5, headY + 7);
    contexto.lineTo(4, headY + 12);
    contexto.lineTo(-4, headY + 12);
    contexto.closePath();
    contexto.fill();
    contexto.strokeStyle = estiloVisual.contorno29;
    contexto.lineWidth = 1;
    contexto.beginPath();
    contexto.moveTo(-2, headY + 10);
    contexto.lineTo(3, headY + 10);
    contexto.stroke();
    contexto.fillStyle = estiloVisual.preenchimento30;
    contexto.shadowColor = estiloVisual.brilho31;
    contexto.shadowBlur = 6;
    contexto.beginPath();
    contexto.moveTo(-7, headY + 3);
    contexto.lineTo(-2, headY + 4);
    contexto.lineTo(-6, headY + 6);
    contexto.closePath();
    contexto.fill();
    contexto.beginPath();
    contexto.moveTo(2, headY + 4);
    contexto.lineTo(7, headY + 3);
    contexto.lineTo(6, headY + 6);
    contexto.closePath();
    contexto.fill();
    contexto.shadowBlur = 0;
    if (this.hurtFlash > 0) {
      contexto.fillStyle = estiloVisual.preenchimento32;
      contexto.beginPath();
      contexto.roundRect(-20, -74, 40, 74, 6);
      contexto.fill();
    }
    if (this.fearTimer > 0) {
      contexto.strokeStyle = estiloVisual.contorno33;
      contexto.lineWidth = 2;
      contexto.beginPath();
      contexto.arc(0, -36, 32 + Math.sin(this.animTime * 10) * 3, 0, Math.PI * 2);
      contexto.stroke();
    }
    contexto.restore();
  }
};
